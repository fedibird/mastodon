import React from 'react';

// A short movement wins over the long-press timer, so an ordinary swipe keeps
// the timeline's native scrolling/momentum. Only a stationary 400ms hold
// redirects the *existing* gesture into the clipped card body.
const HOLD_DELAY_MS = 400;
const MOVE_SLOP_PX = 8;
const INTERACTIVE = 'a, button, input, textarea, select, label, summary, [role="button"], [contenteditable]';

export function canStartCardBodyHold (target, viewport) {
  // The timeline/card container may itself have role="button". Only
  // interactive descendants INSIDE the text viewport should block a hold.
  const interactive = target && target.closest && target.closest(INTERACTIVE);
  return !interactive || !viewport.contains(interactive);
}

export default function useCardBodyHoldScroll (viewportRef, enabled, setHoldActive) {
  React.useEffect(() => {
    const viewport = viewportRef.current;
    if (!enabled || !viewport) {
      setHoldActive(false);
      return undefined;
    }

    let press = null;
    let holdTimer = null;
    // A browser may dispatch click at the common ancestor of mousedown and
    // mouseup. That can be outside this viewport but inside the same card.
    // Capture only the post-release click, then remove the guard.
    const cardClickHost = viewport.closest('.status__wrapper--compact') || viewport;
    let clickGuardTimer = null;
    let listeningForMouse = false;
    let listeningForInterruption = false;

    // Subscribe only during an ongoing press; cards must not accumulate
    // global listeners while idle in a long timeline.
    const stopInterruptionTracking = () => {
      if (listeningForInterruption) {
        window.removeEventListener('blur', onWindowBlur);
        document.removeEventListener('visibilitychange', onVisibilityChange);
        listeningForInterruption = false;
      }
    };

    const stopMouseTracking = () => {
      if (listeningForMouse) {
        document.removeEventListener('mousemove', onMouseMove);
        document.removeEventListener('mouseup', onMouseUp, true);
        listeningForMouse = false;
      }
    };

    const stopTimer = () => {
      if (holdTimer !== null) {
        window.clearTimeout(holdTimer);
        holdTimer = null;
      }
    };

    const release = () => {
      stopTimer();
      stopInterruptionTracking();
      const wasActive = Boolean(press && press.active);
      if (press && press.type === 'mouse') {
        stopMouseTracking();
      }
      press = null;
      if (wasActive) {
        setHoldActive(false);
      }
      return wasActive;
    };

    const onClickCapture = event => {
      clearClickGuard();
      event.preventDefault();
      event.stopPropagation();
    };

    const onNewGesture = () => {
      // A new genuine press is not the click generated by the old gesture.
      // In particular, do not swallow a quick next tap on a card link.
      clearClickGuard();
    };

    const clearClickGuard = () => {
      if (clickGuardTimer !== null) {
        window.clearTimeout(clickGuardTimer);
        clickGuardTimer = null;
      }
      cardClickHost.removeEventListener('click', onClickCapture, true);
      cardClickHost.removeEventListener('pointerdown', onNewGesture, true);
      cardClickHost.removeEventListener('touchstart', onNewGesture, true);
    };

    const suppressGestureClick = type => {
      clearClickGuard();
      cardClickHost.addEventListener('click', onClickCapture, true);
      cardClickHost.addEventListener('pointerdown', onNewGesture, true);
      cardClickHost.addEventListener('touchstart', onNewGesture, true);
      // The mouse click is usually dispatched in the same task as mouseup.
      // Touch browsers may synthesize it later. Do not trap future clicks if
      // the gesture produces no click.
      clickGuardTimer = window.setTimeout(clearClickGuard, type === 'touch' ? 750 : 100);
    };

    const start = (type, identifier, x, y, target) => {
      release();
      clearClickGuard();
      if (!canStartCardBodyHold(target, viewport)) {
        return;
      }

      press = { type, identifier, x, y, lastY: y, active: false };
      window.addEventListener('blur', onWindowBlur);
      document.addEventListener('visibilitychange', onVisibilityChange);
      listeningForInterruption = true;
      holdTimer = window.setTimeout(() => {
        holdTimer = null;
        if (press && press.type === type && press.identifier === identifier) {
          press.active = true;
          setHoldActive(true);
        }
      }, HOLD_DELAY_MS);
    };

    const move = (type, identifier, x, y, event) => {
      if (!press || press.type !== type || press.identifier !== identifier) {
        return;
      }

      if (!press.active) {
        if (Math.hypot(x - press.x, y - press.y) > MOVE_SLOP_PX) {
          release();
        }
        return;
      }

      // Once native panning owns a touch gesture, do not move both the
      // timeline and the inner body. Yield to the browser instead.
      if (type === 'touch' && !event.cancelable) {
        release();
        return;
      }
      event.preventDefault();

      const dy = y - press.lastY;
      viewport.scrollTop -= dy;
      press.lastY = y;
    };

    const onTouchStart = event => {
      if (!event.touches || event.touches.length !== 1) {
        release();
        return;
      }

      const touch = event.touches[0];
      start('touch', touch.identifier, touch.clientX, touch.clientY, event.target);
    };

    const onTouchMove = event => {
      if (!press || press.type !== 'touch') {
        return;
      }

      if (!event.touches || event.touches.length !== 1) {
        release();
        return;
      }

      const touch = event.touches[0];
      move('touch', touch.identifier, touch.clientX, touch.clientY, event);
    };

    const onTouchEnd = () => {
      if (press && press.type === 'touch' && release()) {
        suppressGestureClick('touch');
      }
    };

    const onTouchCancel = () => {
      release();
      clearClickGuard();
    };

    const onMouseDown = event => {
      // Touch browsers may synthesize mousedown/mouseup before the delayed
      // click. Do not replace the pending touch click guard with a mouse press.
      if (event.button === 0 && clickGuardTimer === null) {
        start('mouse', 'primary', event.clientX, event.clientY, event.target);
        if (press && press.type === 'mouse') {
          // Avoid O(number of visible cards) document listeners on every
          // mousemove. Only the card with a pending/active press needs them.
          document.addEventListener('mousemove', onMouseMove);
          document.addEventListener('mouseup', onMouseUp, true);
          listeningForMouse = true;
        }
      }
    };

    const onMouseMove = event => {
      if (!press || press.type !== 'mouse') {
        return;
      }

      if (!(event.buttons & 1)) {
        release();
        return;
      }

      move('mouse', 'primary', event.clientX, event.clientY, event);
    };

    // Capture mouseup before StatusContent.handleMouseUp can open the status.
    // It reacts to small mouse movements even when there is no click handler.
    const onMouseUp = event => {
      if (press && press.type === 'mouse') {
        const wasActive = release();
        if (wasActive) {
          suppressGestureClick('mouse');
          event.preventDefault();
          event.stopPropagation();
        }
      }
    };

    const onContextMenu = event => {
      if (press && press.active) {
        event.preventDefault();
        event.stopPropagation();
      }
    };

    function onWindowBlur () {
      release();
      clearClickGuard();
    }

    function onVisibilityChange () {
      if (document.hidden) {
        release();
        clearClickGuard();
      }
    }

    viewport.addEventListener('touchstart', onTouchStart, { passive: true });
    viewport.addEventListener('touchmove', onTouchMove, { passive: false });
    viewport.addEventListener('touchend', onTouchEnd);
    viewport.addEventListener('touchcancel', onTouchCancel);
    viewport.addEventListener('mousedown', onMouseDown);
    viewport.addEventListener('contextmenu', onContextMenu);
    return () => {
      release();
      viewport.removeEventListener('touchstart', onTouchStart);
      viewport.removeEventListener('touchmove', onTouchMove);
      viewport.removeEventListener('touchend', onTouchEnd);
      viewport.removeEventListener('touchcancel', onTouchCancel);
      viewport.removeEventListener('mousedown', onMouseDown);
      viewport.removeEventListener('contextmenu', onContextMenu);
      stopMouseTracking();
      clearClickGuard();
    };
  }, [enabled, viewportRef, setHoldActive]);
}
